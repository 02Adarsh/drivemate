  /// Every state and union territory, alphabetically sorted.
  static List<String> get states {
    final list = stateCities.keys.toList()..sort();
    return list;
  }

  /// Cities for [state]; empty list when nothing is selected or unknown.
  static List<String> citiesFor(String? state) {
    if (state == null || state.isEmpty) return [];
    final cities = stateCities[state];
    if (cities == null) return [];
    return List<String>.from(cities);
  }

  /// Free-text search across every city (used by the location search field).
  static List<String> searchCities(String query, {int limit = 30}) {
    final text = query.trim().toLowerCase();
    if (text.isEmpty) return [];
    final results = <String>[];
    for (final entry in stateCities.entries) {
      for (final city in entry.value) {
        if (city.toLowerCase().contains(text)) {
          results.add('$city, ${entry.key}');
          if (results.length >= limit) return results;
        }
      }
    }
    return results;
  }
